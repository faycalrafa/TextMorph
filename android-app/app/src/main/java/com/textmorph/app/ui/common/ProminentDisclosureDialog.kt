@OptIn(ExperimentalLayoutApi::class)
@Composable
fun ProminentDisclosureDialog(
    onDismiss: () -> Unit,
    onAcceptAndContinue: () -> Unit
) {
    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Card(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 16.dp, vertical = 24.dp),
            shape = RoundedCornerShape(20.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
            elevation = CardDefaults.cardElevation(defaultElevation = 6.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(20.dp)
                    .verticalScroll(rememberScrollState()),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Icon(
                    imageVector = Icons.Default.Security,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.size(48.dp)
                )

                Spacer(modifier = Modifier.height(12.dp))

                Text(
                    text = "Accessibility Service Disclosure",
                    style = MaterialTheme.typography.titleLarge,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )

                Spacer(modifier = Modifier.height(12.dp))

                Text(
                    text = "TextMorph uses Android's Accessibility Service API to provide on-device writing assistance across all your favorite applications.\n\n" +
                            "• How it is used: When you focus on an editable text input, TextMorph displays a small floating AI toolbar above the field. Tapping a prompt reads the current text and inserts the transformed result.\n\n" +
                            "• Privacy Guarantee: TextMorph runs locally on your device. We NEVER log keystrokes, collect passwords, monitor credit cards, or transmit your personal data to remote tracking servers.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )

                Spacer(modifier = Modifier.height(24.dp))

                FlowRow(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp, Alignment.End),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    OutlinedButton(
                        onClick = onDismiss,
                        shape = RoundedCornerShape(10.dp)
                    ) {
                        Text("Not Now")
                    }
                    Button(
                        onClick = onAcceptAndContinue,
                        shape = RoundedCornerShape(10.dp)
                    ) {
                        Text("Proceed to Settings")
                    }
                }
            }
        }
    }
}
