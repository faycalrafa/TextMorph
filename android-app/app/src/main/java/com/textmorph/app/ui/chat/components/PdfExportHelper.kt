package com.textmorph.app.ui.chat.components

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.os.Environment
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import com.textmorph.app.data.model.ArtifactMetadata
import com.textmorph.app.util.AppLogger
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Exports generated artifacts and research reports to clean, paginated PDF documents
 * saved in the device's Downloads/TextMorph/ directory.
 */
object PdfExportHelper {

    private const val TAG = "PdfExportHelper"
    private const val PAGE_WIDTH = 595 // A4 standard width in points
    private const val PAGE_HEIGHT = 842 // A4 standard height in points
    private const val MARGIN_HORIZONTAL = 40
    private const val MARGIN_VERTICAL = 48
    private const val CONTENT_WIDTH = PAGE_WIDTH - (MARGIN_HORIZONTAL * 2)
    private const val CONTENT_HEIGHT = PAGE_HEIGHT - (MARGIN_VERTICAL * 2)

    suspend fun exportArtifactToPdf(
        context: Context,
        artifact: ArtifactMetadata
    ): Result<File> = withContext(Dispatchers.IO) {
        val pdfDocument = PdfDocument()
        try {
            val titlePaint = TextPaint().apply {
                color = Color.BLACK
                textSize = 18f
                isFakeBoldText = true
                isAntiAlias = true
            }

            val metaPaint = TextPaint().apply {
                color = Color.DKGRAY
                textSize = 10f
                isAntiAlias = true
            }

            val bodyPaint = TextPaint().apply {
                color = Color.BLACK
                textSize = 11.5f
                isAntiAlias = true
            }

            val linePaint = Paint().apply {
                color = Color.LTGRAY
                strokeWidth = 1f
            }

            // Sanitize markdown formatting slightly for clean plain printing
            val cleanBody = artifact.content
                .replace(Regex("""!\[(.*?)\]\((https?://[^\s)]+)\)"""), "[Image: $1]")
                .replace(Regex("""```[a-zA-Z0-9_\-\+]*\n"""), "\n--- Code ---\n")
                .replace(Regex("""```"""), "\n-------------\n")

            val bodyLayout = StaticLayout.Builder.obtain(
                cleanBody,
                0,
                cleanBody.length,
                bodyPaint,
                CONTENT_WIDTH
            ).setAlignment(Layout.Alignment.ALIGN_NORMAL)
                .setLineSpacing(3f, 1.15f)
                .setIncludePad(false)
                .build()

            var pageNumber = 1
            var currentLineIndex = 0
            val totalLines = bodyLayout.lineCount

            while (currentLineIndex < totalLines || pageNumber == 1) {
                val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
                val page = pdfDocument.startPage(pageInfo)
                val canvas = page.canvas

                var cursorY = MARGIN_VERTICAL.toFloat()

                // Header on First Page
                if (pageNumber == 1) {
                    canvas.drawText(artifact.title.take(50), MARGIN_HORIZONTAL.toFloat(), cursorY + 16f, titlePaint)
                    cursorY += 24f

                    val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date(artifact.createdAtMs))
                    val metaLine = "${artifact.type.uppercase()} • $dateStr • Generated by TextMorph"
                    canvas.drawText(metaLine, MARGIN_HORIZONTAL.toFloat(), cursorY + 10f, metaPaint)
                    cursorY += 18f

                    canvas.drawLine(
                        MARGIN_HORIZONTAL.toFloat(),
                        cursorY,
                        (PAGE_WIDTH - MARGIN_HORIZONTAL).toFloat(),
                        cursorY,
                        linePaint
                    )
                    cursorY += 14f
                }

                // Render lines fitting into current page
                val pageAvailableHeight = (PAGE_HEIGHT - MARGIN_VERTICAL) - cursorY
                val startLineForPage = currentLineIndex

                var linesDrawnHeight = 0f
                var endLineForPage = startLineForPage

                while (endLineForPage < totalLines) {
                    val lineBottom = bodyLayout.getLineBottom(endLineForPage)
                    val lineTop = bodyLayout.getLineTop(startLineForPage)
                    val currentHeight = (lineBottom - lineTop).toFloat()

                    if (currentHeight > pageAvailableHeight) {
                        break
                    }
                    linesDrawnHeight = currentHeight
                    endLineForPage++
                }

                if (endLineForPage > startLineForPage) {
                    canvas.save()
                    canvas.translate(MARGIN_HORIZONTAL.toFloat(), cursorY - bodyLayout.getLineTop(startLineForPage))
                    canvas.clipRect(0, bodyLayout.getLineTop(startLineForPage), CONTENT_WIDTH, bodyLayout.getLineBottom(endLineForPage - 1))
                    bodyLayout.draw(canvas)
                    canvas.restore()
                }

                // Footer (Page numbers)
                val footerText = "Page $pageNumber"
                canvas.drawText(
                    footerText,
                    (PAGE_WIDTH - MARGIN_HORIZONTAL - 40).toFloat(),
                    (PAGE_HEIGHT - MARGIN_VERTICAL / 2).toFloat(),
                    metaPaint
                )

                pdfDocument.finishPage(page)
                pageNumber++
                currentLineIndex = if (endLineForPage > startLineForPage) endLineForPage else currentLineIndex + 1
                if (endLineForPage >= totalLines) break
            }

            // Save to Downloads/TextMorph
            val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
            val targetDir = File(downloadsDir, "TextMorph").apply { mkdirs() }
            val safeFileName = artifact.title
                .replace(Regex("[^a-zA-Z0-9._-]"), "_")
                .take(40)
                .trim('_')
                .ifBlank { "TextMorph_Document" }
            val targetFile = File(targetDir, "${safeFileName}_${System.currentTimeMillis()}.pdf")

            FileOutputStream(targetFile).use { out ->
                pdfDocument.writeTo(out)
            }

            AppLogger.i(TAG, "Successfully exported artifact to PDF: ${targetFile.absolutePath}")
            Result.success(targetFile)
        } catch (t: Throwable) {
            AppLogger.e(TAG, "Failed to export PDF: ${t.message}", t)
            Result.failure(t)
        } finally {
            try {
                pdfDocument.close()
            } catch (_: Exception) {}
        }
    }
}
