package com.textmorph.app.agent.artifacts

import com.textmorph.app.util.AppLogger
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

/**
 * Status lifecycle of a planned sub-task section.
 */
enum class SectionStatus {
    PENDING,
    RESEARCHING,
    DRAFTING,
    DONE,
    FAILED
}

/**
 * Definition of a single planned section in an incremental artifact.
 */
data class PlanSection(
    val index: Int,
    val title: String,
    val queryOrGoal: String,
    var status: SectionStatus = SectionStatus.PENDING,
    var content: String = "",
    var retryCount: Int = 0
)

/**
 * Verification outcome of the deterministic Kotlin Quality Gate.
 */
data class QualityGateResult(
    val isValid: Boolean,
    val reason: String = "",
    val wordCount: Int = 0,
    val charCount: Int = 0
)

/**
 * ArtifactAssemblyStore manages order-preserving incremental assembly of long-form
 * artifacts generated by bounded concurrent workers.
 *
 * Staged drafts are backed by a temporary cache file to ensure survival against Android
 * background memory pressure, and section completion is strictly gated by a Kotlin quality gate.
 */
class ArtifactAssemblyStore(
    private val cacheDir: File,
    val sessionId: String
) {

    private val TAG = "ArtifactAssemblyStore"
    private val stateMutex = Mutex()

    private var planGoal: String = ""
    private val sections = mutableMapOf<Int, PlanSection>()
    private val stagingFile = File(cacheDir, "artifact_staging_${sessionId.replace(Regex("[^a-zA-Z0-9_-]"), "_")}.json")

    /**
     * Initializes the store with planned sections.
     */
    suspend fun initSession(goal: String, initialSections: List<PlanSection>) = stateMutex.withLock {
        planGoal = goal
        sections.clear()
        for (sec in initialSections) {
            sections[sec.index] = sec.copy()
        }
        AppLogger.i(TAG, "[$sessionId] Initialized artifact session with ${initialSections.size} sections for goal: '$goal'")
        persistToDisk()
    }

    /**
     * Atomically overwrites the markdown content for a given section index.
     */
    suspend fun writeSection(index: Int, markdown: String): Boolean = stateMutex.withLock {
        val target = sections[index]
        if (target == null) {
            AppLogger.w(TAG, "[$sessionId] writeSection failed: section index $index not found (available: ${sections.keys})")
            return false
        }
        val cleanMarkdown = markdown.trim()
        target.content = cleanMarkdown
        target.status = SectionStatus.DRAFTING
        AppLogger.d(TAG, "[$sessionId] Wrote ${cleanMarkdown.length} chars to section $index: '${target.title}'")
        persistToDisk()
        return true
    }

    /**
     * Atomically appends markdown content to a given section index.
     */
    suspend fun appendSection(index: Int, markdown: String): Boolean = stateMutex.withLock {
        val target = sections[index]
        if (target == null) {
            AppLogger.w(TAG, "[$sessionId] appendSection failed: section index $index not found (available: ${sections.keys})")
            return false
        }
        val cleanMarkdown = markdown.trim()
        target.content = if (target.content.isBlank()) {
            cleanMarkdown
        } else {
            "${target.content}\n\n$cleanMarkdown"
        }
        target.status = SectionStatus.DRAFTING
        AppLogger.d(TAG, "[$sessionId] Appended ${cleanMarkdown.length} chars to section $index (total: ${target.content.length})")
        persistToDisk()
        return true
    }

    /**
     * Updates the execution lifecycle status of a section.
     */
    suspend fun updateStatus(index: Int, status: SectionStatus) = stateMutex.withLock {
        val target = sections[index]
        if (target != null) {
            target.status = status
            AppLogger.d(TAG, "[$sessionId] Updated section $index status to $status")
            persistToDisk()
        }
    }

    /**
     * Retrieves an immutable snapshot of all sections.
     */
    suspend fun getAllSections(): List<PlanSection> = stateMutex.withLock {
        sections.values.sortedBy { it.index }.map { it.copy() }
    }

    /**
     * Retrieves a copy of a specific section.
     */
    suspend fun getSection(index: Int): PlanSection? = stateMutex.withLock {
        sections[index]?.copy()
    }

    /**
     * Evaluates whether a section's drafted content meets the minimum quality requirements.
     */
    fun validateSectionQuality(
        index: Int,
        minWords: Int = 30,
        minChars: Int = 100
    ): QualityGateResult {
        val section = sections[index] ?: return QualityGateResult(
            isValid = false,
            reason = "Section index $index does not exist."
        )

        val trimmed = section.content.trim()
        val words = if (trimmed.isBlank()) emptyList() else trimmed.split(Regex("\\s+"))
        val wordCount = words.size
        val charCount = trimmed.length

        if (charCount < minChars || wordCount < minWords) {
            val reason = "Section $index content is too brief ($wordCount words, $charCount chars; requires >= $minWords words and >= $minChars chars)."
            AppLogger.w(TAG, "[$sessionId] Quality gate failed for section $index: $reason")
            return QualityGateResult(
                isValid = false,
                reason = reason,
                wordCount = wordCount,
                charCount = charCount
            )
        }

        // Check for boilerplate stub text
        val lower = trimmed.lowercase()
        if (lower.startsWith("todo") || lower.startsWith("tbd") || lower.startsWith("section content goes here")) {
            val reason = "Section $index contains placeholder boilerplate instead of researched content."
            AppLogger.w(TAG, "[$sessionId] Quality gate failed for section $index: $reason")
            return QualityGateResult(
                isValid = false,
                reason = reason,
                wordCount = wordCount,
                charCount = charCount
            )
        }

        AppLogger.i(TAG, "[$sessionId] Quality gate PASSED for section $index ($wordCount words, $charCount chars).")
        return QualityGateResult(
            isValid = true,
            reason = "Content meets quality standards.",
            wordCount = wordCount,
            charCount = charCount
        )
    }

    /**
     * Checks if all planned sections have achieved DONE status.
     */
    suspend fun areAllSectionsCompleted(): Boolean = stateMutex.withLock {
        sections.isNotEmpty() && sections.values.all { it.status == SectionStatus.DONE }
    }

    /**
     * Compiles the finished artifact in strict section order and cleans up disk staging.
     */
    suspend fun compileFinalArtifact(): String = stateMutex.withLock {
        val sorted = sections.values.sortedBy { it.index }
        val sb = StringBuilder()

        if (planGoal.isNotBlank()) {
            sb.append("# ").append(planGoal).append("\n\n")
        }

        // Table of contents
        if (sorted.size > 1) {
            sb.append("### Table of Contents\n")
            for (sec in sorted) {
                sb.append("- Section ${sec.index}: **${sec.title}**\n")
            }
            sb.append("\n---\n\n")
        }

        // Sections in strict order
        for (sec in sorted) {
            sb.append("## ${sec.index}. ${sec.title}\n\n")
            if (sec.content.isNotBlank()) {
                sb.append(sec.content.trim()).append("\n\n")
            } else {
                sb.append("*(Content generation incomplete for this section)*\n\n")
            }
        }

        AppLogger.i(TAG, "[$sessionId] Successfully compiled final artifact (${sb.length} chars across ${sorted.size} sections)")
        cleanupStagingFile()
        return sb.toString().trim()
    }

    /**
     * Persists active staging state to a cache file atomically.
     */
    private suspend fun persistToDisk() = withContext(Dispatchers.IO) {
        try {
            val root = JSONObject()
            root.put("sessionId", sessionId)
            root.put("planGoal", planGoal)

            val array = JSONArray()
            for (sec in sections.values.sortedBy { it.index }) {
                val obj = JSONObject()
                obj.put("index", sec.index)
                obj.put("title", sec.title)
                obj.put("queryOrGoal", sec.queryOrGoal)
                obj.put("status", sec.status.name)
                obj.put("content", sec.content)
                obj.put("retryCount", sec.retryCount)
                array.put(obj)
            }
            root.put("sections", array)

            val temp = File(cacheDir, "${stagingFile.name}.tmp")
            temp.writeText(root.toString(), Charsets.UTF_8)
            if (temp.exists()) {
                temp.renameTo(stagingFile)
            }
        } catch (t: Throwable) {
            AppLogger.e(TAG, "[$sessionId] Failed to persist artifact staging state to disk: ${t.message}", t)
        }
    }

    /**
     * Cleans up staging file upon successful final assembly.
     */
    private suspend fun cleanupStagingFile() = withContext(Dispatchers.IO) {
        try {
            if (stagingFile.exists()) {
                stagingFile.delete()
                AppLogger.d(TAG, "[$sessionId] Staging cache file deleted.")
            }
        } catch (t: Throwable) {
            AppLogger.w(TAG, "[$sessionId] Could not delete staging file: ${t.message}")
        }
    }
}
